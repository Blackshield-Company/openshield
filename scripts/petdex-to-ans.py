#!/usr/bin/env python3
"""Convert the blackshield-knight petdex spritesheet into OpenShield .ans sprites.

Samples the 8px-cell grid, quantizes colors to the Blackshield theme palette
(emitted as theme tokens for fg + truecolor ANSI for half-block bg), and
renders half-block art. Outputs:
  - assets/sprites/blackshield-mercenary.ans       (splash, 2x horizontal)
  - assets/sprites/blackshield-mercenary-mini.ans  (corner mascot, downsampled)
"""
import os
from PIL import Image

SHEET = os.path.expanduser("~/.hermes/pets/blackshield-knight/spritesheet.webp")
OUT_DIR = os.path.expanduser("~/Projects/active/openshield/assets/sprites")

CELL = 8
COLS, ROWS = 24, 26

# Source sheet palette -> (emit_rgb_for_halfblock_bg, fg_emit_string)
# Theme tokens where they fit (theme-tracking), raw truecolor where the
# theme has no suitable color (navy armor, maroon sigil must stay readable
# on black terminals — {bg} alone would be invisible).
REFS = [
    ((27, 31, 40), (43, 50, 69), "\x1b[38;2;43;50;69m"),    # navy armor
    ((13, 16, 23), (13, 13, 17), "{bg}"),                   # void outline
    ((143, 163, 189), (138, 143, 152), "{muted}"),          # steel trim -> ash
    ((220, 229, 242), (216, 211, 200), "{bone}"),           # blade/belt -> bone
    ((224, 85, 95), (193, 18, 31), "{accent}"),             # crest/visor/cross -> blood
    ((255, 107, 114), (193, 18, 31), "{accent}"),           # bright red -> blood
    ((142, 47, 56), (142, 47, 56), "\x1b[38;2;142;47;56m"),  # maroon sigil
]


def nearest(r, g, b):
    ref, emit_rgb, fg = min(
        REFS, key=lambda p: (r - p[0][0]) ** 2 + (g - p[0][1]) ** 2 + (b - p[0][2]) ** 2
    )
    return (emit_rgb, fg)


def cell_color(frame, cx, cy):
    """Majority opaque color in the cell, quantized to palette name."""
    counts = {}
    for y in range(cy * CELL, (cy + 1) * CELL):
        for x in range(cx * CELL, (cx + 1) * CELL):
            r, g, b, a = frame.getpixel((x, y))
            if a > 128:
                counts.setdefault((r, g, b), 0)
                counts[(r, g, b)] += 1
    if not counts:
        return None
    r, g, b = max(counts, key=counts.get)
    return nearest(r, g, b)


def grid(frame):
    return [[cell_color(frame, cx, cy) for cx in range(COLS)] for cy in range(ROWS)]


def trim(g):
    xs = [x for row in g for x, c in enumerate(row) if c]
    ys = [y for y, row in enumerate(g) for x, c in enumerate(row) if c]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    return [row[x0 : x1 + 1] for row in g[y0 : y1 + 1]]


def render(g, hscale=1):
    """Half-block render: two cell rows per terminal row. ▀ fg=top, bg=bottom."""
    lines = []
    for y in range(0, len(g) - 1, 2):
        top_row, bot_row = g[y], g[y + 1]
        out = []
        for t, b in zip(top_row, bot_row):
            if t and b:
                (tr, tg, tb), tfg = t
                (br, bg_, bb), _ = b
                ch = tfg + f"\x1b[48;2;{br};{bg_};{bb}m" + "▀" * hscale + "{reset}"
            elif t:
                ch = t[1] + "▀" * hscale + "{reset}"
            elif b:
                ch = b[1] + "▄" * hscale + "{reset}"
            else:
                ch = " " * hscale
            out.append(ch)
        lines.append("".join(out).rstrip())
    # Odd row count: dangling last row as top-half blocks
    if len(g) % 2 == 1:
        out = []
        for t in g[-1]:
            out.append(t[1] + "▀" * hscale + "{reset}" if t else " " * hscale)
        lines.append("".join(out).rstrip())
    return lines


def downsample(g):
    """2x downsample by majority vote over 2x2 cell blocks."""
    h, w = len(g), len(g[0])
    out = []
    for y in range(0, h - 1, 2):
        row = []
        for x in range(0, w - 1, 2):
            block = [g[y][x], g[y][x + 1], g[y + 1][x], g[y + 1][x + 1]]
            solid = [c for c in block if c]
            if not solid:
                row.append(None)
            else:
                row.append(max(set(solid), key=solid.count))
        out.append(row)
    return out


def main():
    im = Image.open(SHEET)
    frames = []
    for col in (0, 3):  # idle frame 0 + idle frame 3 (crest sway)
        f = im.crop((col * 192, 0, (col + 1) * 192, 208))
        frames.append(trim(grid(f)))

    # Pad both frames to the same cell dims (union bbox)
    H = max(len(f) for f in frames)
    W = max(len(f[0]) for f in frames)
    frames = [[row + [None] * (W - len(row)) for row in f] + [[None] * W] * (H - len(f)) for f in frames]

    # Big sprite: half-block, 2x horizontal
    big = ["---frame---".join("\n".join(render(f, hscale=2)) + "\n" for f in frames)]
    # Mini: same grid, half-block, 1x horizontal (16 cols — petdex size)
    mini = ["---frame---".join("\n".join(render(f, hscale=1)) + "\n" for f in frames)]

    header_big = (
        "# blackshield-mercenary — pixel-accurate conversion of the\n"
        "# blackshield-knight petdex pet (idle f0 + f3, crest sway).\n"
        "# Generated by scripts/petdex-to-ans.py — edit the script, not the art.\n"
    )
    header_mini = header_big.replace("blackshield-mercenary —", "blackshield-mercenary-mini —")

    with open(os.path.join(OUT_DIR, "blackshield-mercenary.ans"), "w") as f:
        f.write(header_big + big[0])
    with open(os.path.join(OUT_DIR, "blackshield-mercenary-mini.ans"), "w") as f:
        f.write(header_mini + mini[0])

    import re
    for name, text in [("big", big[0]), ("mini", mini[0])]:
        for i, fr in enumerate(text.split("---frame---")):
            stripped = [re.sub(r"\{[^}]*\}", "", l) for l in fr.splitlines() if not l.startswith("#")]
            stripped = [re.sub(r"\x1b\[[0-9;]*m", "", l) for l in stripped]
            w = max((len(l) for l in stripped), default=0)
            print(f"{name} frame{i}: {len(stripped)} rows x {w} cols")
            print("\n".join(stripped))
            print()


main()
